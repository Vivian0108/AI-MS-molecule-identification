"""Deterministic evidence features for candidate ranking (SpectraPilot v3).

Every value is computed from observed peaks, candidate structure and the
template store.  Nothing is generated by a language model, and the evaluator
truth is never read.  Missing evidence is represented as ``None`` (NaN in the
ranker matrix) rather than as a negative observation.

The feature set deliberately keeps *what a measurement supports* separate from
*how much the template can be trusted*: a poor structure-kNN template is not
chemical counter-evidence.
"""

from __future__ import annotations

from typing import Iterable, Mapping, Sequence

import numpy as np
from pydantic import BaseModel, Field

from spectrapilot.models import Candidate, Template
from spectrapilot.science.fragments import SubformulaBackend
from unknownid.core.spectra import (
    cosine_greedy,
    matched_peaks,
    neutral_loss_agreement,
    neutral_losses,
)

DEFAULT_ACTIONS = ("CID20", "CID40", "EAD16")


class EvidenceFeatures(BaseModel):
    """Features for one (candidate, action) pair.  See spec §3.2."""

    candidate_id: str
    action_key: str
    precursor_ppm: float
    cosine: float | None = None
    matched_peak_count: int = 0
    matched_intensity_fraction: float = 0.0
    unexplained_high_intensity_fraction: float = 1.0
    neutral_loss_support: float | None = None
    chemically_valid_subformula_fraction: float | None = None
    neutral_loss_chemically_valid_fraction: float | None = None
    diagnostic_peak_support: float | None = None
    template_source: str = "missing"
    template_energy_offset_ev: float | None = None
    predicted_template_reliability: float = 0.0
    n_template_donors: int = 0
    observation_peak_count: int = 0
    observation_quality_flags: list[str] = Field(default_factory=list)
    # Extra provenance used by reports and the UI.
    explained_intensity_fraction: float | None = None
    template_is_experimental: bool = False
    method_validated: bool = True
    provenance: dict = Field(default_factory=dict)

    def public_dict(self) -> dict:
        return {
            "candidate_id": self.candidate_id,
            "action_key": self.action_key,
            "precursor_ppm": self.precursor_ppm,
            "cosine": self.cosine,
            "matched_peak_count": self.matched_peak_count,
            "matched_intensity_fraction": self.matched_intensity_fraction,
            "unexplained_high_intensity_fraction": self.unexplained_high_intensity_fraction,
            "neutral_loss_support": self.neutral_loss_support,
            "chemically_valid_subformula_fraction": self.chemically_valid_subformula_fraction,
            "neutral_loss_chemically_valid_fraction": self.neutral_loss_chemically_valid_fraction,
            "diagnostic_peak_support": self.diagnostic_peak_support,
            "template_source": self.template_source,
            "template_energy_offset_ev": self.template_energy_offset_ev,
            "predicted_template_reliability": self.predicted_template_reliability,
            "n_template_donors": self.n_template_donors,
            "observation_peak_count": self.observation_peak_count,
            "observation_quality_flags": list(self.observation_quality_flags),
            "explained_intensity_fraction": self.explained_intensity_fraction,
            "template_is_experimental": self.template_is_experimental,
            "method_validated": self.method_validated,
            "provenance": self.provenance,
        }


class CaseFeatures(BaseModel):
    """Case-level context available before any follow-up measurement."""

    n_candidates: int = 1
    unique_candidate: int = 0
    precursor_ppm_best: float = 0.0
    precursor_ppm_spread: float = 0.0
    formula_competitor_count: int = 0
    connectivity_competitor_count: int = 0
    initial_support: float = 0.0
    initial_margin: float = 0.0
    max_template_reliability: float = 0.0
    min_template_reliability: float = 0.0
    predecessor_peaks: int = 0


class EvidenceFeatureExtractor:
    """Compute :class:`EvidenceFeatures` for candidate/action pairs."""

    def __init__(
        self,
        *,
        tolerance_da: float = 0.02,
        ppm_tolerance: float = 10.0,
        unexplained_floor: float = 0.01,
        max_observed_peaks: int = 24,
        truncate_peaks: bool = True,
        fragments: SubformulaBackend | None = None,
    ) -> None:
        self.tolerance_da = float(tolerance_da)
        self.ppm_tolerance = float(ppm_tolerance)
        self.unexplained_floor = float(unexplained_floor)
        self.max_observed_peaks = int(max_observed_peaks)
        self.truncate_peaks = bool(truncate_peaks)
        self.fragments = fragments if fragments is not None else SubformulaBackend(
            ppm_tolerance=self.ppm_tolerance, enabled=False
        )

    # -- observation quality ----------------------------------------------
    def _observation_flags(self, mz: np.ndarray, intensity: np.ndarray) -> list[str]:
        flags: list[str] = []
        if mz.size < 3:
            flags.append("too_few_peaks")
        elif mz.size < 5:
            flags.append("few_peaks")
        total = float(intensity.sum()) if intensity.size else 0.0
        if intensity.size and total > 0 and float(intensity.max()) / total > 0.9:
            flags.append("dominant_base_peak")
        if mz.size and float(mz.max()) < 90.0:
            flags.append("no_high_mass_fragments")
        return flags

    @staticmethod
    def _top_peaks(
        mz: np.ndarray, intensity: np.ndarray, limit: int
    ) -> tuple[np.ndarray, np.ndarray]:
        if limit <= 0 or mz.size <= limit:
            return mz, intensity
        order = np.argsort(-intensity)[:limit]
        order.sort()
        return mz[order], intensity[order]

    # -- main extraction ---------------------------------------------------
    def extract(
        self,
        *,
        action_key: str,
        observed_mz: Sequence[float],
        observed_intensity: Sequence[float],
        candidate: Candidate,
        template: Template | None,
        precursor_mz: float,
    ) -> EvidenceFeatures:
        mz, intensity = self._top_peaks(
            np.asarray(observed_mz, float),
            np.asarray(observed_intensity, float),
            self.max_observed_peaks if self.truncate_peaks else 0,
        )
        flags = self._observation_flags(mz, intensity)
        nominal_energy = float(str(action_key).lstrip("CIDEA")) if action_key else 0.0
        fragmentation = "EAD" if str(action_key).startswith("EAD") else "CID"

        features = EvidenceFeatures(
            candidate_id=candidate.molecule_id,
            action_key=str(action_key),
            precursor_ppm=(
                (candidate.precursor_mz - precursor_mz) / precursor_mz * 1e6
                if precursor_mz
                else 0.0
            ),
            observation_peak_count=int(mz.size),
            observation_quality_flags=flags,
        )

        if template is None or template.n_peaks == 0:
            features.template_source = "missing"
            features.provenance = {"template": "no template for this action"}
            return features

        features.template_source = template.source
        features.template_is_experimental = template.is_experimental
        features.predicted_template_reliability = float(template.reliability)
        features.n_template_donors = int(template.n_donors)
        if template.expected_energy_ev is not None:
            features.template_energy_offset_ev = float(template.expected_energy_ev) - nominal_energy

        if mz.size == 0:
            return features

        cosine, n_matched = cosine_greedy(
            mz, intensity, template.mz, template.intensity, self.tolerance_da
        )
        features.cosine = float(cosine)
        features.matched_peak_count = int(n_matched)

        matches = matched_peaks(
            mz, intensity, template.mz, template.intensity, self.tolerance_da
        )
        kept = intensity >= self.unexplained_floor
        denominator = float(intensity[kept].sum()) or 1.0
        matched_intensity = sum(
            item["observed_intensity"] for item in matches
            if item["observed_intensity"] >= self.unexplained_floor
        )
        features.matched_intensity_fraction = float(
            np.clip(matched_intensity / denominator, 0.0, 1.0)
        )
        features.unexplained_high_intensity_fraction = float(
            np.clip(1.0 - features.matched_intensity_fraction, 0.0, 1.0)
        )

        # Neutral-loss agreement and chemical plausibility of those losses.
        observed_losses = neutral_losses(mz, intensity, precursor_mz)
        template_losses = neutral_losses(template.mz, template.intensity, precursor_mz)
        agreement, n_loss = neutral_loss_agreement(
            observed_losses, template_losses, self.tolerance_da
        )
        features.neutral_loss_support = float(agreement)

        if n_loss and self.fragments.method_supported(fragmentation):
            plausible = 0
            checked = 0
            for loss, _ in observed_losses:
                verdict = self.fragments.loss_is_plausible(
                    loss, formula=candidate.formula, tolerance_da=self.tolerance_da
                )
                if verdict is None:
                    continue
                checked += 1
                plausible += int(verdict)
            if checked:
                features.neutral_loss_chemically_valid_fraction = plausible / checked

        # Candidate-formula peak explanation (CID only; EAD is not validated).
        explanation = self.fragments.explain_peaks(
            mz,
            intensity,
            formula=candidate.formula,
            adduct=candidate.adduct,
            fragmentation=fragmentation,
        )
        if explanation is not None:
            features.chemically_valid_subformula_fraction = (
                explanation.n_explained / max(explanation.n_observed_peaks, 1)
            )
            features.explained_intensity_fraction = explanation.explained_intensity_fraction
            features.method_validated = explanation.method_validated
            features.provenance["subformula_backend"] = explanation.backend
        else:
            features.provenance["subformula_backend"] = "unavailable_or_unvalidated_for_method"

        return features

    # -- vectorisation -----------------------------------------------------
    def vector(self, features: EvidenceFeatures) -> dict[str, float]:
        return features_to_vector(features)


#: Stable column order for the ranker.  Changing it invalidates trained models.
ACTION_FEATURE_KEYS = (
    "present",
    "cosine",
    "matched_peak_count",
    "matched_intensity_fraction",
    "unexplained_high_intensity_fraction",
    "neutral_loss_support",
    "chemically_valid_subformula_fraction",
    "neutral_loss_chemically_valid_fraction",
    "predicted_template_reliability",
    "template_is_experimental",
    "template_energy_offset_ev",
    "log1p_n_template_donors",
    "log1p_observation_peak_count",
)

CASE_FEATURE_KEYS = (
    "n_candidates",
    "unique_candidate",
    "precursor_ppm_best",
    "precursor_ppm_spread",
    "formula_competitor_count",
    "connectivity_competitor_count",
    "initial_support",
    "initial_margin",
    "max_template_reliability",
    "min_template_reliability",
    "log1p_predecessor_peaks",
)


def _clean(value: float | None) -> float:
    if value is None:
        return float("nan")
    try:
        return float(value)
    except (TypeError, ValueError):
        return float("nan")


def features_to_vector(features: EvidenceFeatures) -> dict[str, float]:
    return {
        "present": 1.0,
        "cosine": _clean(features.cosine),
        "matched_peak_count": float(features.matched_peak_count),
        "matched_intensity_fraction": _clean(features.matched_intensity_fraction),
        "unexplained_high_intensity_fraction": _clean(
            features.unexplained_high_intensity_fraction
        ),
        "neutral_loss_support": _clean(features.neutral_loss_support),
        "chemically_valid_subformula_fraction": _clean(
            features.chemically_valid_subformula_fraction
        ),
        "neutral_loss_chemically_valid_fraction": _clean(
            features.neutral_loss_chemically_valid_fraction
        ),
        "predicted_template_reliability": _clean(
            features.predicted_template_reliability
        ),
        "template_is_experimental": float(features.template_is_experimental),
        "template_energy_offset_ev": _clean(features.template_energy_offset_ev),
        "log1p_n_template_donors": float(np.log1p(features.n_template_donors)),
        "log1p_observation_peak_count": float(
            np.log1p(features.observation_peak_count)
        ),
    }


def missing_action_vector() -> dict[str, float]:
    """A row for an action that has not been measured (explicit missing mask)."""
    row = {key: float("nan") for key in ACTION_FEATURE_KEYS}
    row["present"] = 0.0
    return row


def case_features(
    *,
    candidates: Sequence[Candidate],
    weights: Mapping[str, float] | None = None,
    template_reliabilities: Mapping[str, float] | None = None,
    precursor_ppm_by_candidate: Mapping[str, float] | None = None,
    predecessor_peaks: int = 0,
) -> CaseFeatures:
    weights = dict(weights or {})
    ordered_weights = sorted(weights.values(), reverse=True)
    support = float(ordered_weights[0]) if ordered_weights else 0.0
    margin = (
        float(ordered_weights[0] - ordered_weights[1]) if len(ordered_weights) > 1 else 0.0
    )
    formulas: dict[str, int] = {}
    for candidate in candidates:
        formulas[candidate.formula] = formulas.get(candidate.formula, 0) + 1
    connectivity: dict[str, int] = {}
    for candidate in candidates:
        connectivity[candidate.connectivity_key] = (
            connectivity.get(candidate.connectivity_key, 0) + 1
        )
    ppm_values = sorted(
        abs(float(value)) for value in (precursor_ppm_by_candidate or {}).values()
    )
    reliabilities = list((template_reliabilities or {}).values())
    return CaseFeatures(
        n_candidates=len(candidates),
        unique_candidate=int(len(candidates) == 1),
        precursor_ppm_best=ppm_values[0] if ppm_values else 0.0,
        precursor_ppm_spread=(ppm_values[-1] - ppm_values[0]) if ppm_values else 0.0,
        formula_competitor_count=max(formulas.values()) if formulas else 0,
        connectivity_competitor_count=max(connectivity.values()) if connectivity else 0,
        initial_support=support,
        initial_margin=margin,
        max_template_reliability=max(reliabilities) if reliabilities else 0.0,
        min_template_reliability=min(reliabilities) if reliabilities else 0.0,
        predecessor_peaks=int(predecessor_peaks),
    )


def case_features_to_vector(features: CaseFeatures) -> dict[str, float]:
    return {
        "n_candidates": float(features.n_candidates),
        "unique_candidate": float(features.unique_candidate),
        "precursor_ppm_best": float(features.precursor_ppm_best),
        "precursor_ppm_spread": float(features.precursor_ppm_spread),
        "formula_competitor_count": float(features.formula_competitor_count),
        "connectivity_competitor_count": float(features.connectivity_competitor_count),
        "initial_support": float(features.initial_support),
        "initial_margin": float(features.initial_margin),
        "max_template_reliability": float(features.max_template_reliability),
        "min_template_reliability": float(features.min_template_reliability),
        "log1p_predecessor_peaks": float(np.log1p(features.predecessor_peaks)),
    }


def feature_columns(actions: Sequence[str] = DEFAULT_ACTIONS) -> list[str]:
    """Full, versioned feature-column list for a scoring sequence."""
    columns = list(CASE_FEATURE_KEYS)
    for action in actions:
        columns.extend(f"{action}__{key}" for key in ACTION_FEATURE_KEYS)
    return columns


def build_sequence_row(
    *,
    per_action: Mapping[str, EvidenceFeatures],
    case: CaseFeatures,
    actions: Sequence[str] = DEFAULT_ACTIONS,
) -> dict[str, float]:
    """Flatten a candidate's evidence across the observed sequence."""
    row = case_features_to_vector(case)
    for action in actions:
        prefix = f"{action}__"
        features = per_action.get(action)
        if features is None:
            for key, value in missing_action_vector().items():
                row[f"{prefix}{key}"] = value
        else:
            for key, value in features_to_vector(features).items():
                row[f"{prefix}{key}"] = value
    return row
